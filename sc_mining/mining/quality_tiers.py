def _norm(name):
    n = (name or "").strip()
    for suf in (" (Ore)", " (Raw)", " Ore", " (Pure)"):
        if n.endswith(suf):
            n = n[: -len(suf)]
    return {"ice": "pressurized ice"}.get(n.lower(), n.lower())     # 制造表里叫 Ice（老大审查 2026-10-28）


